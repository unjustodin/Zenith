#!/usr/bin/env python3
"""Records a small piece of the mock server's world for the client's main-menu background.

    python3 tools/mock_server.py --port 34590 &
    python3 tools/record_menu_world.py --port 34590

Plays a client: says hello, waits for the prototypes, subscribes to the chunks around the
mock's starter factory and keeps what arrives for a few seconds (prototypes, chunks, entities,
machine states, items on belts, inserter hands, moving things), each with its time. The messages go to
client/data/menu_world.json, which client/scripts/menu/menu_background.gd replays into a world
mirror with no server. Everything in it is generated by the mock (numbers, prototype names):
nothing of Factorio's.
"""

import argparse
import json
import pathlib
import socket
import time

KEEP = {"protos", "tprotos", "iprotos", "fprotos", "chunk", "ents", "st", "bi", "mv", "ih", "gi", "wires", "fl", "pw"}
OUT = pathlib.Path(__file__).resolve().parent.parent / "client" / "data" / "menu_world.json"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=34590)
    ap.add_argument("--center", default="0,0", help="chunk at the middle, cx,cy")
    ap.add_argument("--radius", type=int, default=2, help="chunks around it")
    ap.add_argument("--seconds", type=float, default=8.0)
    args = ap.parse_args()
    cx, cy = (int(v) for v in args.center.split(","))
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, 4 * 1024 * 1024)
    sock.bind(("127.0.0.1", 0))
    sock.settimeout(0.05)
    dest = ("127.0.0.1", args.port)

    def send(msg):
        sock.sendto(json.dumps(msg).encode(), dest)

    kept = []
    seen_kinds = {}
    ready = False
    subscribed_at = None
    last_hello = 0.0
    chunks = [[cx + dx, cy + dy] for dy in range(-args.radius, args.radius + 1) for dx in range(-args.radius, args.radius + 1)]
    started = time.time()
    while True:
        now = time.time()
        if now - last_hello > 1.0:
            send({"t": "hello", "v": 1, "sid": "menu-recorder", "w": 1 if ready else 0})
            last_hello = now
        if ready and subscribed_at is None:
            send({"t": "sub", "c": chunks})
            send({"t": "focus", "x": (cx * 32 + 16) * 256, "y": (cy * 32 + 16) * 256, "r": 48})
            subscribed_at = now
        if subscribed_at is not None and now - subscribed_at > args.seconds:
            break
        if now - started > 60:
            raise SystemExit("no answer from the mock on port %d" % args.port)
        try:
            data, _ = sock.recvfrom(1 << 20)
        except socket.timeout:
            continue
        msg = json.loads(data)
        t = msg.get("t")
        if t == "ready":
            ready = True
        if t in KEEP:
            msg.pop("r", None)
            # Seconds after subscribing: live updates are replayed on this clock, in a loop.
            msg["dt"] = round(now - subscribed_at, 3) if subscribed_at is not None else 0.0
            kept.append(msg)
            seen_kinds[t] = seen_kinds.get(t, 0) + 1
    send({"t": "bye"})
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"center": [cx * 32 + 16, cy * 32 + 16], "messages": kept}, separators=(",", ":")))
    print("wrote %s: %d messages, %d bytes, %s" % (OUT, len(kept), OUT.stat().st_size, seen_kinds))


if __name__ == "__main__":
    main()
